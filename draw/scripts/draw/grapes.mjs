import { bench, ellipse } from './lib.mjs';

// ================================================================ 포도 — 참조 없음(직접 디자인)
// 가운데 세로줄 알을 먼저 그어 높이를 정하고, 양옆으로 알을 붙여 거꾸로 선 세모 송이를 만듭니다.
export default function draw() {
  const b = bench();
  const g = (pts, tag) => pts.map(([x, y], i) => b.closed(`${tag}${i}`, ellipse(x, y, 25, 25, 10)));
  const mid = g([[200, 193], [200, 279], [200, 365]], 'm');
  b.step('가운데 알', '종이 가운데에 동그란 포도알을 세로로 세 개 그려요.', ...mid);

  const left = g([[175, 150], [150, 193], [175, 236], [150, 279], [175, 322]], 'l');
  b.step('왼쪽 알', '가운데 알 왼쪽에 붙여서 포도알을 다섯 개 그려요.', ...left);

  const right = g([[225, 150], [250, 193], [225, 236], [250, 279], [225, 322]], 'r');
  b.step('오른쪽 알', '가운데 알 오른쪽에도 포도알을 다섯 개 그려요.', ...right);

  const outer = g([[125, 150], [100, 193], [125, 236], [275, 150], [300, 193], [275, 236]], 'o');
  b.step('바깥 알', '양쪽 바깥에 포도알을 세 개씩 더 그려요.', ...outer);

  const stem = b.closed('stem', [[194, 146], [192, 112], [196, 80], [206, 76], [208, 86], [204, 114], [206, 146]], 0.6);
  b.step('꼭지', '포도송이 맨 위에 짧은 꼭지를 그려요.', stem);

  const leaf = b.closed('leaf', [[208, 104], [230, 82], [262, 70], [298, 74], [284, 100], [254, 116], [222, 118]], 0.9);
  const vein = b.open('vein', [[214, 110], [248, 96], [290, 78]], ['leaf', 'leaf']);
  b.step('잎', '꼭지 옆에 잎을 그리고 가운데에 잎맥을 그어요.', leaf, vein);

  const shine = [[190, 182], [165, 139], [240, 182], [140, 268]].map(([x, y], i) => b.closed(`sh${i}`, ellipse(x, y, 4, 6, 8, -0.5)));
  b.step('반짝이', '포도알 몇 개에 작은 반짝이를 그려요.', ...shine);

  return {
    id: 'grapes', title: '포도', theme: 'food', difficulty: 'easy', grades: ['lower'],
    paper: 'portrait', viewBox: '0 0 400 500',
    setupSay: '종이를 세로로 놓고, 가운데에 포도알부터 하나씩 그릴 거예요.',
    coloringSeconds: 150, steps: b.steps, keywords: ['과일', '음식', '가을'],
  };
}
