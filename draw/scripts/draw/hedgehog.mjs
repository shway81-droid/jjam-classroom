import { bench, ellipse } from './lib.mjs';

// ================================================================ 고슴도치 — 참조 없음(직접 디자인), 옆에서 본 모습
// 코가 뾰족한 몸을 먼저 긋고, 가시는 등 위를 지나가는 지그재그 한 획으로 몸에 양 끝을 붙입니다.
export default function draw() {
  const b = bench();
  const body = b.closed('body', [[90, 250], [100, 190], [150, 150], [220, 135], [290, 150], [340, 180], [400, 225], [420, 240], [400, 254], [340, 280], [260, 300], [170, 300], [110, 285]], 0.8);
  b.step('몸', '종이 가운데에 코가 뾰족한 둥근 몸을 그려요.', body);

  const spikes = b.open('spikes', [
    [98, 262], [58, 238], [100, 222], [70, 182], [118, 190], [102, 138], [148, 162], [150, 104], [190, 148],
    [206, 88], [232, 142], [262, 94], [272, 148], [312, 112], [306, 162],
  ], ['body', 'body'], 0);
  b.step('가시', '몸 위쪽을 따라 뾰족뾰족한 가시를 그려요.', spikes);

  const ear = b.open('ear', [[326, 174], [332, 154], [350, 158], [356, 190]], ['body', 'body']);
  b.step('귀', '가시 오른쪽 끝에 작고 둥근 귀를 그려요.', ear);

  const eye = b.closed('eye', ellipse(366, 212, 7, 9));
  b.step('눈', '귀 앞쪽 아래에 동그란 눈을 그려요.', eye);

  const nose = b.closed('nose', ellipse(416, 240, 9, 8));
  b.step('코', '뾰족한 끝에 동그란 코를 그려요.', nose);

  const mouth = b.closed('mouth', [[380, 256], [392, 262], [402, 256], [398, 266], [390, 269], [384, 265]], 0.8);
  b.step('입', '코 아래쪽에 작게 웃는 입을 그려요.', mouth);

  const cheek = b.closed('cheek', ellipse(360, 246, 11, 7));
  b.step('볼', '눈 아래에 발그레한 볼을 그려요.', cheek);

  const feet = [[146, 170], [196, 220], [262, 286], [308, 332]].map(([a, z], i) => b.open(`f${i}`, [[a, 296], [a - 4, 318], [(a + z) / 2 - 2, 324], [z, 318], [z + 2, 296]], ['body', 'body']));
  b.step('발', '몸 아래에 짧고 둥근 발을 네 개 그려요.', ...feet);

  const apple = b.closed('apple', [[455, 290], [470, 284], [482, 296], [482, 316], [470, 334], [455, 330], [440, 334], [428, 316], [428, 296], [440, 284]], 0.9);
  b.step('사과', '코 앞 아래쪽에 동그란 사과를 그려요.', apple);

  const st = b.closed('st', [[453, 290], [452, 274], [458, 268], [460, 276], [458, 290]], 0.5);
  const lf = b.closed('lf', [[460, 280], [474, 266], [488, 266], [480, 280]], 0.8);
  b.step('사과 꼭지', '사과 위에 짧은 꼭지와 잎을 그려요.', st, lf);

  return {
    id: 'hedgehog', title: '고슴도치', theme: 'animal', difficulty: 'normal', grades: ['middle'],
    paper: 'landscape', viewBox: '0 0 500 400',
    setupSay: '종이를 가로로 놓고, 가운데에 손바닥만큼 큰 몸부터 그릴 거예요.',
    coloringSeconds: 180, steps: b.steps, keywords: ['동물', '숲', '가을'],
  };
}
