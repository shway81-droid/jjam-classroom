import { bench, ellipse } from './lib.mjs';

// ================================================================ 딸기 — 참조 없음(직접 디자인)
// 위가 넓고 아래가 뾰족한 열매를 첫 획으로, 꼭지 잎·씨는 열매 위에 얹습니다.
export default function draw() {
  const b = bench();
  const berry = b.closed('berry', [[110, 172], [200, 152], [290, 172], [322, 232], [302, 320], [252, 400], [200, 440], [148, 400], [98, 320], [78, 232]]);
  b.step('열매', '종이 가운데에 위가 넓고 아래가 뾰족한 열매를 그려요.', berry);

  const leaves = b.closed('leaves', [[124, 164], [158, 132], [176, 152], [200, 116], [224, 152], [242, 132], [276, 164], [240, 180], [200, 172], [160, 180]], 0.5);
  b.step('꼭지 잎', '열매 꼭대기에 뾰족한 잎을 별처럼 둘러 그려요.', leaves);

  const stem = b.closed('stem', [[195, 124], [192, 92], [202, 86], [210, 92], [206, 124]], 0.6);
  b.step('꼭지', '잎 가운데 위에 짧은 꼭지를 그려요.', stem);

  const seed = (x, y, i) => b.closed(`sd${i}`, ellipse(x, y, 5, 8));
  const s1 = [[140, 230], [200, 220], [260, 230], [120, 290], [180, 280], [240, 280]].map(([x, y], i) => seed(x, y, i));
  b.step('씨 하나', '열매 위쪽에 작은 씨를 여섯 개 그려요.', ...s1);

  const s2 = [[280, 290], [150, 340], [210, 336], [262, 340], [180, 392], [228, 392]].map(([x, y], i) => seed(x, y, i + 6));
  b.step('씨 둘', '열매 아래쪽에도 작은 씨를 여섯 개 그려요.', ...s2);

  const shine = b.closed('shine', [[108, 244], [116, 222], [130, 212], [128, 226], [120, 246]], 0.7);
  b.step('반짝', '열매 왼쪽 위에 반짝이는 작은 빛을 그려요.', shine);

  return {
    id: 'strawberry', title: '딸기', theme: 'food', difficulty: 'easy', grades: ['lower'],
    paper: 'portrait', viewBox: '0 0 400 500',
    setupSay: '종이를 세로로 놓고, 가운데에 손바닥만큼 큰 열매부터 그릴 거예요.',
    coloringSeconds: 150, steps: b.steps, keywords: ['음식', '과일', '딸기'],
  };
}
