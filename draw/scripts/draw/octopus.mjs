import { bench, ellipse } from './lib.mjs';

// ================================================================ 문어 — 참조 없음(직접 디자인), 앞을 보고 웃습니다
// 둥근 머리를 첫 획으로, 다리는 머리 아래에서 내려가 끝을 말고 다시 머리로 올라오는 긴 획입니다.
export default function draw() {
  const b = bench();
  const head = b.closed('head', [
    [200, 70], [262, 84], [304, 130], [314, 196], [298, 252], [260, 286],
    [200, 294], [140, 286], [102, 252], [86, 196], [96, 130], [138, 84],
  ]);
  b.step('둥근 머리', '종이 위쪽 가운데에 크고 둥근 머리를 그려요.', head);

  const leg = (name, pts) => b.open(name, pts, ['head', 'head'], 0.9);
  const l1 = leg('l1', [[116, 268], [96, 318], [100, 360], [74, 404], [52, 414], [62, 436], [92, 424], [126, 372], [126, 326], [152, 290]]);
  const l2 = leg('l2', [[166, 292], [150, 352], [162, 408], [146, 440], [166, 456], [190, 432], [188, 398], [178, 352], [198, 294]]);
  b.step('왼쪽 다리', '머리 아래 왼쪽에 끝이 말린 다리를 두 개 그려요.', l1, l2);

  const l3 = leg('l3', [[204, 294], [224, 352], [212, 398], [210, 432], [234, 456], [254, 440], [238, 408], [250, 352], [234, 292]]);
  const l4 = leg('l4', [[248, 290], [274, 326], [274, 372], [308, 424], [338, 436], [348, 414], [326, 404], [300, 360], [304, 318], [284, 268]]);
  b.step('오른쪽 다리', '머리 아래 오른쪽에도 끝이 말린 다리를 두 개 그려요.', l3, l4);

  const eyeL = b.closed('eyeL', ellipse(160, 184, 16, 21));
  const eyeR = b.closed('eyeR', ellipse(240, 184, 16, 21));
  b.step('눈 두 개', '머리 가운데에 동그란 눈을 두 개 그려요.', eyeL, eyeR);

  const mouth = b.closed('mouth', ellipse(200, 236, 12, 10));
  b.step('동그란 입', '두 눈 사이 아래에 호 하고 부는 동그란 입을 그려요.', mouth);

  const cheekL = b.closed('cheekL', ellipse(128, 228, 16, 10));
  const cheekR = b.closed('cheekR', ellipse(272, 228, 16, 10));
  b.step('볼 두 개', '입 양옆에 발그레한 볼을 동그랗게 그려요.', cheekL, cheekR);

  return {
    id: 'octopus', title: '문어', theme: 'animal', difficulty: 'easy', grades: ['lower'],
    paper: 'portrait', viewBox: '0 0 400 500',
    setupSay: '종이를 세로로 놓고, 위쪽 가운데에 손바닥만큼 큰 머리부터 그릴 거예요.',
    coloringSeconds: 150, steps: b.steps, keywords: ['동물', '바다', '문어'],
  };
}
