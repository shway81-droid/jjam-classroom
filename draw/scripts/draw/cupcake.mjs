import { bench, ellipse } from './lib.mjs';

// ================================================================ 컵케이크 — 참조 없음(직접 디자인)
// 몽실몽실한 크림을 첫 획으로 크게 긋고, 컵은 크림 아래 양 끝에 붙인 한 획입니다.
export default function draw() {
  const b = bench();
  const frost = b.closed('frost', [[92, 305], [86, 272], [110, 246], [104, 214], [134, 188], [150, 156], [186, 136], [214, 134], [248, 156], [268, 188], [296, 214], [292, 246], [314, 272], [308, 305], [200, 310]], 0.8);
  b.step('크림', '종이 가운데에 몽실몽실한 크림을 크게 그려요.', frost);

  const cup = b.open('cup', [[112, 306], [126, 380], [138, 450], [200, 452], [262, 450], [274, 380], [288, 306]], ['frost', 'frost'], 0.4);
  b.step('컵', '크림 아래에 아래가 좁은 컵을 그려요.', cup);

  const pl = [[[146, 308], [154, 448]], [[176, 309], [180, 450]], [[224, 309], [220, 450]], [[254, 308], [246, 448]]]
    .map((p, i) => b.open(`pl${i}`, p, ['frost', 'cup']));
  b.step('컵 주름', '컵에 위에서 아래로 줄을 네 개 그어요.', ...pl);

  const t1 = b.open('t1', [[104, 252], [200, 266], [296, 252]], ['frost', 'frost']);
  const t2 = b.open('t2', [[132, 196], [200, 208], [270, 196]], ['frost', 'frost']);
  b.step('크림 줄', '크림 안에 둥근 가로줄을 두 개 그어요.', t1, t2);

  const cherry = b.closed('cherry', ellipse(200, 112, 23, 22, 10));
  b.step('체리', '크림 꼭대기에 동그란 체리를 올려요.', cherry);

  const stem = b.closed('stem', [[203, 91], [208, 70], [222, 54], [228, 59], [216, 74], [210, 93]], 0.6);
  b.step('체리 꼭지', '체리 위에 휘어진 꼭지를 그려요.', stem);

  const shine = b.closed('shine', ellipse(191, 104, 4, 7, 8, 0.5));
  b.step('반짝이', '체리 왼쪽 위에 작은 반짝이를 그려요.', shine);

  const sp = (pts, tag) => pts.map(([x, y, r], i) => b.closed(`${tag}${i}`, ellipse(x, y, 9, 3.2, 8, r)));
  const sp1 = sp([[170, 170, 0.6], [228, 174, -0.5], [196, 232, 0.2], [256, 228, 0.9]], 'a');
  b.step('스프링클', '크림 위쪽에 길쭉한 스프링클을 네 개 그려요.', ...sp1);

  const sp2 = sp([[136, 282, -0.7], [184, 290, 0.4], [226, 286, -0.3], [268, 282, 0.7]], 'b');
  b.step('스프링클 더', '크림 아래쪽에도 스프링클을 네 개 더 그려요.', ...sp2);

  return {
    id: 'cupcake', title: '컵케이크', theme: 'food', difficulty: 'normal', grades: ['middle'],
    paper: 'portrait', viewBox: '0 0 400 500',
    setupSay: '종이를 세로로 놓고, 가운데에 손바닥만큼 큰 크림부터 그릴 거예요.',
    coloringSeconds: 180, steps: b.steps, keywords: ['음식', '간식', '생일'],
  };
}
