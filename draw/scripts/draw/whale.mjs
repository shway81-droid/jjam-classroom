import { bench, ellipse } from './lib.mjs';

// ================================================================ 고래 — 참조 없음(직접 디자인), 왼쪽을 보고 물을 뿜습니다
// 통통한 몸을 첫 획으로, 꼬리·배·지느러미는 몸에 붙입니다. 물방울을 먼저 그리고 물줄기로 잇습니다.
export default function draw() {
  const b = bench();
  const body = b.closed('body', [
    [80, 214], [92, 164], [130, 124], [200, 106], [280, 110], [340, 132],
    [380, 162], [402, 194], [412, 216], [404, 240], [380, 264], [330, 286],
    [260, 298], [180, 298], [120, 282], [90, 252],
  ]);
  b.step('통통한 몸', '종이 가운데에 앞이 둥글고 뒤가 좁은 큰 몸을 그려요.', body);

  const tail = b.open('tail', [[404, 206], [428, 178], [440, 140], [458, 112], [482, 126], [474, 154], [482, 184], [462, 202], [410, 220]], ['body', 'body'], 0.8);
  b.step('꼬리', '몸 뒤 끝에 위로 들린 꼬리를 그려요.', tail);

  const eye = b.closed('eye', ellipse(150, 178, 9, 11));
  b.step('눈', '몸 앞쪽 위에 동그란 눈을 하나 그려요.', eye);

  const mouth = b.closed('mouth', [[104, 220], [140, 232], [176, 230], [168, 242], [140, 246], [114, 236]], 0.8);
  b.step('웃는 입', '눈 아래에 길게 웃는 입을 그려요.', mouth);

  const cheek = b.closed('cheek', ellipse(186, 210, 15, 9));
  b.step('볼', '입 끝 위에 발그레한 볼을 하나 그려요.', cheek);

  const belly = b.open('belly', [[92, 252], [150, 272], [230, 280], [310, 276], [338, 284]], ['body', 'body']);
  b.step('배 줄', '몸 아래쪽에 배를 나누는 긴 줄을 그어요.', belly);

  const stripes = [150, 200, 250].map((x, i) => b.open(`st${i}`, [[x, 276], [x, 300]], ['belly', 'body']));
  b.step('배 무늬', '배 줄 아래에 짧은 줄을 세 개 그어요.', ...stripes);

  const fin = b.open('fin', [[204, 278], [228, 302], [262, 326], [276, 310], [262, 290], [246, 280]], ['belly', 'belly'], 0.8);
  b.step('지느러미', '배 가운데 아래에 작은 지느러미를 그려요.', fin);

  const drops = [[166, 58, 10], [200, 36, 12], [234, 58, 10]].map(([x, y, r], i) => b.closed(`dr${i}`, [
    [x, y - r * 1.6], [x + r * 0.8, y - r * 0.2], [x + r, y + r * 0.5], [x, y + r * 1.1], [x - r, y + r * 0.5], [x - r * 0.8, y - r * 0.2],
  ], 0.8));
  b.step('물방울', '머리 위 하늘에 물방울을 세 개 그려요.', ...drops);

  const spout = b.open('spout', [[200, 108], [200, 80], [200, 52]], ['body', 'dr1']);
  b.step('물줄기', '머리 꼭대기에서 가운데 물방울까지 줄을 그어요.', spout);

  return {
    id: 'whale', title: '고래', theme: 'animal', difficulty: 'normal', grades: ['middle'],
    paper: 'landscape', viewBox: '0 0 500 400',
    setupSay: '종이를 가로로 놓고, 가운데에 손바닥만큼 큰 몸부터 그릴 거예요.',
    coloringSeconds: 180, steps: b.steps, keywords: ['동물', '바다', '고래'],
  };
}
